    if affiliation == "高等教育":
        fallback = {
            "本科高校": ("rgb(255,255,0)", "160000"),
            "专科": ("rgb(255,255,0)", "160000"),
            "校内学院": ("rgb(51, 255, 187)", "100000"),
            "校内建筑": ("rgb(51, 255, 187)", "100000"),
        }
